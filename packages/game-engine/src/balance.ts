// Every balance number from the MVP rules (01 - MVP.md) lives here.
// Values are provisional: tune them here and nowhere else.
//
// Units:
// - Territory and business production, bonuses and Economic Value are in points.
//   Money points are converted to $ with `moneyUnit`. Other resources are 1 point = 1 unit.
// - Every money cost is in $.
// - Percentages are fractions: 0.15 means +15%, -0.2 means -20%.

import type {
  AcquirableTerritoryType,
  BusinessType,
  CharacterId,
  InstitutionalTerritoryType,
  ResourceKey,
  ResourcePool,
  TerritoryType,
} from '@under-control/shared';
import { MAX_POLICE_ATTENTION, STANDARD_ROUNDS } from '@under-control/shared';

// Inclusive integer range.
export type Range = {
  min: number;
  max: number;
};

export type ResourceRanges = Record<ResourceKey, Range>;

// Changes the production of the territories it applies to.
export type ProductionModifier = {
  resource: ResourceKey;
  appliesTo: readonly TerritoryType[] | 'all';
  // Fraction added to the territory's production of `resource`.
  percent?: number;
  // Points added to the territory's production of `resource`.
  flat?: number;
};

// Effect a territory has on its adjacent territories.
// Acquirable territories only affect adjacent territories with the same owner.
// Institutional territories affect every adjacent territory.
export type AdjacencyEffect = {
  defense?: number;
  production?: readonly ProductionModifier[];
  // Fraction of defense damage (attacks, sabotage, police) prevented.
  damageReduction?: number;
  // Fraction off the money cost of expansions launched from the adjacent territory.
  acquisitionCostReduction?: number;
  // Fraction added to gang member power when used from or to defend the adjacent territory.
  gangEffectiveness?: number;
  // Fraction added to Police Attention generated by illegal actions (attack, sabotage,
  // infiltration) that target the adjacent territory.
  illegalActionAttention?: number;
  // Police Attention added each round to the owner of each adjacent territory.
  policeAttentionPerRound?: number;
};

// Effects of a special zone on the zone itself.
export type SpecialZoneEffect = {
  defense?: number;
  damageReduction?: number;
  // Fraction off the money cost of the owner's first expansion each round. Does not stack.
  firstExpansionDiscount?: number;
  // Fraction off the money cost of the owner's infiltrations. Does not stack.
  infiltrationDiscount?: number;
};

export type CharacterModifiers = {
  // Territory types the starting territory is picked from, in order of preference.
  startingTerritoryTypes: readonly AcquirableTerritoryType[];
  production: readonly ProductionModifier[];
  // Fraction added to the money cost of every expansion.
  expansionCost: number;
  // Fraction off the money cost of the first expansion each round.
  firstExpansionDiscount: number;
  // Fraction off the money cost of infiltrations.
  infiltrationDiscount: number;
  // Fraction added to all Police Attention the character receives.
  policeAttentionReceived: number;
  // Fraction added to Police Attention generated by territories and businesses each round.
  economicPoliceAttention: number;
  // Defense added to each owned territory per adjacent owned territory.
  defensePerOwnedNeighbor: number;
  // Gang members discounted from each sabotage.
  sabotageGangDiscount: number;
  favorsIncome: { amount: number; everyRounds: number } | null;
};

export type BusinessConfig = {
  // $.
  cost: number;
  // Points per round at level 1.
  production: ResourcePool;
  policeAttentionPerRound: number;
  allowedTerritoryTypes: readonly AcquirableTerritoryType[];
};

export type PoliceRaidChance = {
  // Highest Police Attention of the band, inclusive.
  maxAttention: number;
  chance: number;
};

export type Balance = {
  moneyUnit: number;
  startingResources: ResourcePool;
  setupDieSides: number;

  rounds: number;
  planningDurationMs: number;
  executionDurationMs: number;

  territoryProduction: Record<AcquirableTerritoryType, ResourceRanges>;
  territoryResistance: Record<AcquirableTerritoryType, Range>;
  // Police Attention added each round to the owner, per owned territory of the type.
  territoryPoliceAttentionPerRound: Partial<Record<AcquirableTerritoryType, number>>;
  baseDefensePerResistance: number;

  economicValueWeights: ResourcePool;
  acquisitionCost: { base: number; perEconomicValue: number };

  neighborBonuses: Record<AcquirableTerritoryType, AdjacencyEffect>;
  specialZoneEffects: Partial<Record<AcquirableTerritoryType, SpecialZoneEffect>>;
  institutionalEffects: Record<InstitutionalTerritoryType, AdjacencyEffect>;

  characters: Record<CharacterId, CharacterModifiers>;

  businesses: Record<BusinessType, BusinessConfig>;
  business: {
    maxLevel: number;
    // Upgrade cost as a multiple of the base cost, indexed by target level - 2.
    upgradeCostMultipliers: readonly number[];
    // Production multiplier indexed by level - 1.
    levelProductionMultipliers: readonly number[];
    defaultSlots: number;
    slots: Partial<Record<AcquirableTerritoryType, number>>;
  };

  expansion: {
    // Acquisition Power = influence × influence weight + gang members × gang weight.
    powerWeights: { influence: number; gangMembers: number };
    // Money cost multiplier for the 1st, 2nd, ... acquisition in the same round.
    costMultipliers: readonly number[];
    // Added per acquisition after the last entry of costMultipliers.
    extraCostMultiplierStep: number;
  };

  infiltration: {
    moneyCostMultiplier: number;
    requiredInfluencePerResistance: number;
    policeAttention: Range;
    baseDefensePenalty: number;
    penaltyRounds: number;
  };

  attack: {
    powerWeights: { influence: number; gangMembers: number };
    attackerPoliceAttention: number;
  };

  sabotage: {
    // Defense removed per gang member when weakening.
    weakenStrengthPerGangMember: number;
    // Police Attention added to the target per gang member when stirring up.
    stirUpAttentionPerGangMember: number;
    saboteurPoliceAttention: number;
  };

  cedeTerritory: {
    policeAttentionReduction: number;
    favors: number;
  };

  police: {
    maxAttention: number;
    raidChances: readonly PoliceRaidChance[];
    basePower: number;
    randomPower: Range;
    attentionPerPower: number;
    patrolCarPower: number;
    patrolCarAdjacentPower: number;
    // Police Attention removed from a player per Favor spent.
    attentionPerFavor: number;
  };

  score: {
    perTerritory: number;
    perBusiness: number;
    perInfluence: number;
    // Raw Score += money / moneyPerPoint.
    moneyPerPoint: number;
  };
};

const range = (min: number, max: number): Range => ({ min, max });

const NONE = range(0, 0);

const production = (ranges: Partial<ResourceRanges>): ResourceRanges => ({
  money: NONE,
  influence: NONE,
  gangMembers: NONE,
  favors: NONE,
  ...ranges,
});

const resources = (pool: Partial<ResourcePool>): ResourcePool => ({
  money: 0,
  influence: 0,
  gangMembers: 0,
  favors: 0,
  ...pool,
});

